const LOCAL_STORAGE_KEY = 'spamguard_ml_dataset_v1';

export function loadDataset(): EmailSample[] {
  try {
    const raw = localStorage.getItem(LOCAL_STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
  } catch {
    // fallback to benchmark
  }
  return [...BENCHMARK_EMAILS];
}

export function saveDataset(dataset: EmailSample[]): void {
  try {
    localStorage.setItem(LOCAL_STORAGE_KEY, JSON.stringify(dataset));
  } catch (err) {
    console.error('Failed to save dataset to localStorage', err);
  }
}

export function resetDataset(): EmailSample[] {
  try {
    localStorage.removeItem(LOCAL_STORAGE_KEY);
  } catch {
    // ignore
  }
  return [...BENCHMARK_EMAILS];
}
